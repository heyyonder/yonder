val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// The upload key for Google Play. Google re-signs the app with its own key.
val uploadProperties = Properties().apply {
    val propFile = file("${System.getProperty("user.home")}/.config/yonder/android-upload.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    compileSdk = 37
    namespace = "com.vladartym.yonder"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        // The DSN of Sentry, from SENTRY_DSN at build time. Only the official builds have it. Empty turns Sentry off.
        manifestPlaceholders["sentryDsn"] = System.getenv("SENTRY_DSN") ?: ""
        // The package name of the Play app (so.yonder). The Kotlin code keeps the package com.vladartym.yonder of the
        // identifier in tauri.conf.json, where Tauri writes its generated files.
        applicationId = "so.yonder"
        minSdk = 24
        targetSdk = 37
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    signingConfigs {
        if (uploadProperties.containsKey("storeFile")) {
            create("upload") {
                storeFile = file(uploadProperties.getProperty("storeFile"))
                storePassword = uploadProperties.getProperty("storePassword")
                keyAlias = uploadProperties.getProperty("keyAlias")
                keyPassword = uploadProperties.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            manifestPlaceholders["sentryDsn"] = "" // A debug build sends no crashes.
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            signingConfigs.findByName("upload")?.let { signingConfig = it }
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

